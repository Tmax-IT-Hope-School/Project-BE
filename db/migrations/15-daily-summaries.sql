-- 이미 테이블이 있는 Neon DB 에 "하루 요약표"(이슈 #34) 표를 더하는 SQL 입니다.
--
-- 무엇이 생기나요?
--   daily_summaries            : 한 줄 = 한 사람의 하루치 요약 (순공 · 달성률 · 체크인 값 …)
--   daily_summary_subjects     : 한 줄 = 그 요약의 과목 하나와 순공(분). 과목 없이 공부한 시간은 subject_id 가 비어 있음
--   daily_summary_stop_reasons : 한 줄 = 그 요약의 멈춘 이유 하나와 횟수
--
-- 누가 · 언제 실행하나요?
--   이 표들은 서로만 가리켜서, 01 ~ 14 를 어디까지 실행했든 그대로 실행해도 됩니다.
--   Neon 콘솔 → 브랜치 고르기 → SQL Editor 에 이 파일 전체를 붙여 넣고 Run.
--   dev 브랜치는 지금 바로, main 브랜치는 이 PR 이 들어간 develop → main 배포 **전에** 실행합니다.
--   (이 표가 없으면 예약 작업 daily-summary 와 /api/v1/jobs/daily-summary/rebuild 가 500 입니다)
--
-- 여러 번 실행해도 되나요?
--   네. "없으면 만들기(if not exists)" 와 "있으면 지우고 다시 걸기(외래키)" 뿐입니다. (MigrationSqlTest 가 검사)
--   begin ~ commit 으로 묶여 있어서, 중간에 에러가 나면 하나도 바뀌지 않습니다.
--
-- 탈퇴하면 이 표의 그 사람 줄도 지워집니다. (AccountService.withdraw 가 user_id 가 있는 표를 모두 돎)

begin;

-- 1) 한 사람의 하루치 요약 = 한 줄
create table if not exists daily_summaries (
    achievement_rate integer,
    average_session_minutes integer not null,
    average_start_delay_minutes integer,
    completed_session_count integer not null,
    condition integer,
    day_of_week integer not null,
    expected_minutes integer not null,
    mood integer,
    pause_count integer not null,
    play_actual_minutes integer not null,
    play_planned_minutes integer not null,
    session_count integer not null,
    sleep_minutes integer,
    stop_progress_percent integer,
    study_minutes integer not null,
    suggestion_kept boolean,
    summary_date date not null,
    target_session_count integer not null,
    first_start_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    user_id bigint not null,
    miss_reason varchar(20) check ((miss_reason in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','PROCRASTINATED','ETC'))),
    primary key (id),
    constraint uk_daily_summaries_user_id_summary_date unique (user_id, summary_date)
);

-- 2) 멈춘 이유 = 이유마다 한 줄
create table if not exists daily_summary_stop_reasons (
    position integer not null check ((position>=0)),
    stop_count integer not null,
    daily_summary_id bigint not null,
    stop_reason varchar(20) not null check ((stop_reason in ('TIRED','EVENT','PHONE','TOO_MUCH','UNWILLING','SICK','PROCRASTINATED','ETC'))),
    primary key (daily_summary_id, position)
);

-- 3) 과목별 순공 = 과목마다 한 줄
create table if not exists daily_summary_subjects (
    position integer not null check ((position>=0)),
    study_minutes integer not null,
    daily_summary_id bigint not null,
    subject_id bigint,
    primary key (daily_summary_id, position)
);

alter table daily_summary_stop_reasons drop constraint if exists fk_daily_summary_stop_reasons_daily_summary_id;
alter table daily_summary_stop_reasons
   add constraint fk_daily_summary_stop_reasons_daily_summary_id
   foreign key (daily_summary_id)
   references daily_summaries (id);

alter table daily_summary_subjects drop constraint if exists fk_daily_summary_subjects_daily_summary_id;
alter table daily_summary_subjects
   add constraint fk_daily_summary_subjects_daily_summary_id
   foreign key (daily_summary_id)
   references daily_summaries (id);

commit;
