begin;

-- 1) 설정 근거: 사용자 한 명의 설정 칸 하나 = 한 줄
create table if not exists setting_sources (
    locked boolean not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    source varchar(10) not null check ((source in ('TEST','DATA','USER'))),
    field varchar(30) not null,
    reason varchar(100) not null,
    primary key (id),
    constraint uk_setting_sources_user_id_field unique (user_id, field)
);

-- 2) 말투 수위도 "높이면 다음 날부터"
alter table care_settings add column if not exists pending_max_harshness integer;
alter table care_settings add column if not exists pending_harshness_effective_date date;
alter table care_settings drop constraint if exists ck_care_settings_pending_max_harshness;
alter table care_settings
   add constraint ck_care_settings_pending_max_harshness
   check (pending_max_harshness is null or pending_max_harshness between 1 and 5);

-- 3) 바꾼 기록에 "누가"
alter table setting_changes add column if not exists source varchar(10);
update setting_changes set source = 'USER' where source is null;
alter table setting_changes alter column source set not null;
alter table setting_changes drop constraint if exists ck_setting_changes_source;
alter table setting_changes
   add constraint ck_setting_changes_source
   check (source in ('TEST','DATA','USER'));

commit;
